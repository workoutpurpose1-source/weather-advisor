"""
database.py
============
This file handles EVERYTHING related to our SQLite database.

Why a separate file?
  Keeping database code in its own file (instead of mixing it into app.py)
  makes the project easier to read and maintain. app.py just calls the
  functions defined here, without needing to know HOW the database works.

What this file does:
  1. Creates a database file called "weather.db" (if it doesn't exist yet).
  2. Creates a table called "searches" to store every search a user makes.
  3. Provides two functions:
       - save_search(...)  -> inserts a new row into the table
       - get_history()     -> reads all past rows back out
"""

import sqlite3
import os

# This builds a path to weather.db that sits right next to this file,
# no matter where you run the script from.
DB_PATH = os.path.join(os.path.dirname(os.path.abspath(__file__)), "weather.db")


def init_db():
    """
    Creates the 'searches' table if it does not already exist.
    Call this once when the Flask app starts up.

    Columns explained:
      id            -> unique auto-incrementing ID for each search
      name          -> the user's name
      city          -> city they asked about
      date          -> date of the planned activity
      time          -> time of the planned activity
      activity      -> what they're doing (Picnic, Wedding, Cricket, etc.)
      temperature   -> temperature returned by OpenWeather (in °C)
      condition     -> weather condition text (e.g. "light rain")
      humidity      -> humidity percentage
      wind_speed    -> wind speed in meters/second
      ai_advice     -> the full text advice generated by the AI
      created_at    -> timestamp of when the search was made (auto-filled)
    """
    conn = sqlite3.connect(DB_PATH)
    cursor = conn.cursor()
    cursor.execute("""
        CREATE TABLE IF NOT EXISTS searches (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            name TEXT NOT NULL,
            city TEXT NOT NULL,
            date TEXT NOT NULL,
            time TEXT NOT NULL,
            activity TEXT NOT NULL,
            temperature REAL,
            condition TEXT,
            humidity INTEGER,
            wind_speed REAL,
            ai_advice TEXT,
            created_at TEXT DEFAULT CURRENT_TIMESTAMP
        )
    """)
    conn.commit()
    conn.close()


def save_search(name, city, date, time, activity,
                 temperature, condition, humidity, wind_speed, ai_advice):
    """
    Inserts one new row into the 'searches' table.
    This is called every time a user successfully gets AI advice.
    """
    conn = sqlite3.connect(DB_PATH)
    cursor = conn.cursor()
    cursor.execute("""
        INSERT INTO searches
            (name, city, date, time, activity, temperature, condition,
             humidity, wind_speed, ai_advice)
        VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
    """, (name, city, date, time, activity, temperature, condition,
          humidity, wind_speed, ai_advice))
    conn.commit()
    conn.close()


def get_history(limit=20):
    """
    Returns the most recent searches (default: last 20), newest first.
    Used by the /api/history endpoint so the frontend can show a
    "recent searches" list if desired.
    """
    conn = sqlite3.connect(DB_PATH)
    # row_factory lets us get dictionary-like rows instead of plain tuples
    conn.row_factory = sqlite3.Row
    cursor = conn.cursor()
    cursor.execute("""
        SELECT * FROM searches
        ORDER BY id DESC
        LIMIT ?
    """, (limit,))
    rows = cursor.fetchall()
    conn.close()
    # Convert each sqlite3.Row into a normal Python dictionary
    return [dict(row) for row in rows]
